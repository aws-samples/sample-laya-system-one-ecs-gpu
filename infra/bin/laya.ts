#!/usr/bin/env node
import { App, Aspects, Tags } from 'aws-cdk-lib';
import { LayaStack } from '../lib/laya-stack';

const app = new App();
const env = { account: process.env.CDK_DEFAULT_ACCOUNT, region: 'us-east-1' };

const bool = (key: string) => String(app.node.tryGetContext(key)) === 'true';

const stack = new LayaStack(app, 'Laya', {
  env,
  withPlayground: bool('withPlayground'),
  enableExecuteCommand: bool('enableExecuteCommand'),
  bedrockModels: [
    { label: 'Amazon Nova Micro', id: 'amazon.nova-micro-v1:0' },
    { label: 'Amazon Nova Lite', id: 'amazon.nova-lite-v1:0' },
  ],
  availabilityZones: app.node.tryGetContext('availabilityZones'),
});

Tags.of(app).add('project', 'laya-101');

// Security scan: `npx cdk synth -c nag=true` applies the cdk-nag AwsSolutions rule pack
// and writes the report to cdk.out/AwsSolutions-Laya-NagReport.csv. Off by default, so deploys
// don't depend on cdk-nag (scripts/security-scans.sh installs it without touching package.json).
if (bool('nag')) {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { AwsSolutionsChecks, NagSuppressions } = require('cdk-nag');
  Aspects.of(app).add(new AwsSolutionsChecks({ verbose: true, reports: true }));

  // Reviewed findings. Each one is either a CDK/ECS-generated permission that AWS only accepts
  // with a wildcard, or a trade-off documented in the README.
  const suppress = (path: string, rules: object[]) =>
    NagSuppressions.addResourceSuppressionsByPath(stack, `/Laya/${path}`, rules);

  suppress('Cluster/Resource', [{
    id: 'AwsSolutions-ECS4',
    reason: 'Sample with a single task: Container Insights is left off to avoid extra CloudWatch '
      + 'cost. Application logs and ECS Exec session logs already go to CloudWatch Logs.',
  }]);
  suppress('TaskDef/Resource', [{
    id: 'AwsSolutions-ECS2',
    reason: 'Environment variables hold only non-sensitive configuration (bind address, port, '
      + 'model ids, region). The sample uses no secrets; the task role provides AWS credentials.',
  }]);
  suppress('GpuCapacity/GpuCapacityRole/Resource', [{
    id: 'AwsSolutions-IAM4',
    reason: 'AWS managed policy required by the ECS Managed Instances infrastructure role, '
      + 'attached by the CDK ManagedInstancesCapacityProvider construct.',
    appliesTo: ['Policy::arn:<AWS::Partition>:iam::aws:policy/AmazonECSInfrastructureRolePolicyForManagedInstances'],
  }]);
  suppress('GpuCapacity/InstanceRole/Resource', [{
    id: 'AwsSolutions-IAM5',
    reason: 'Instance role generated by the CDK for the ECS container agent. The agent actions '
      + '(e.g. ecs:DiscoverPollEndpoint) accept only resource "*", and container instance ARNs '
      + 'are assigned at runtime. Calls stay in-account through the ECS VPC endpoint policies.',
    appliesTo: [
      'Resource::*',
      { regex: '/^Resource::arn:<AWS::Partition>:ecs:.*:container-instance\\/\\*$/g' },
    ],
  }]);
  // The task role only gets an inline DefaultPolicy when ECS Exec is enabled (CDK adds the
  // ssmmessages/logs permissions then); the Bedrock grant is a customer managed policy. With
  // Exec off (the default) there is no DefaultPolicy to suppress.
  if (bool('enableExecuteCommand')) {
    suppress('TaskRole/DefaultPolicy/Resource', [{
      id: 'AwsSolutions-IAM5',
      reason: 'Permissions added by the CDK for ECS Exec: the ssmmessages channel actions and '
        + 'logs:DescribeLogGroups accept only resource "*"; session log streams are created at '
        + 'runtime inside the ExecLogs group, so the ARN ends in ":*" (that group only).',
      appliesTo: [
        'Resource::*',
        { regex: '/^Resource::arn:<AWS::Partition>:logs:.*:log-group:<ExecLogs[0-9A-F]+>:\\*$/g' },
      ],
    }]);
  }
  suppress('ExecutionRole/DefaultPolicy/Resource', [{
    id: 'AwsSolutions-IAM5',
    reason: 'ecr:GetAuthorizationToken accepts only resource "*" (AWS design). Image pulls are '
      + 'scoped to the CDK asset repository, and the ECR endpoint policies keep calls in-account.',
    appliesTo: ['Resource::*'],
  }]);
}
